const RECIPE_ICONS = { breakfast: "☼", soup: "♨", main: "◈", salad: "❋", side: "◇", dessert: "○", snack: "▰" };
const PANTRY_INGREDIENTS = new Set(["соль", "масло", "вода", "черный перец"]);

function inferRecipeCuisine(recipe) {
  const searchable = `${recipe.name} ${recipe.ingredients.join(" ")}`.toLowerCase().replace(/ё/g, "е");
  const cuisines = new Set();
  const matches = pattern => pattern.test(searchable);

  if (matches(/паста|спагетти|лазанья|пицца/)) cuisines.add("italian");
  if (matches(/фунчоза|рисовая лапша|лапша с говядиной|соевый соус/)) cuisines.add("asian");
  if (matches(/плов|куриные шашлычки|рис с курицей|перловка с мясом/)) cuisines.add("central-asian");
  if (matches(/курица в томатном соусе|фасоль в томатном соусе|баклажаны с помидорами и сыром|овощи на гриле/)) cuisines.add("georgian");
  if (matches(/лосось с лимоном|форель на гриле|паста с тунцом|паста с кабачками|паста с баклажанами|салат с сыром и свежими овощами|салат с нутом|овощи на гриле/)) cuisines.add("mediterranean");
  if (matches(/хумус|нут с|закуска из нута|чечевичный суп|кускус|фаршированные перцы/)) cuisines.add("middle-eastern");
  if (matches(/бефстроганов|гуляш|драник|жюльен|шарлотка|рассольник|борщ|щи |пюре|сырник|блин|гренк|пирог|запеканк/)) cuisines.add("european");

  const nationalCuisines = ["european", "asian", "italian", "central-asian", "georgian", "mediterranean", "middle-eastern"];
  if (!nationalCuisines.some(cuisine => cuisines.has(cuisine))) cuisines.add("home");
  if (recipe.time <= 30) cuisines.add("quick");
  if (recipe.methodType === "steam" || recipe.methodType === "grill" || recipe.mealType === "salad" || (recipe.methodType === "no-cook" && recipe.mealType !== "dessert")) cuisines.add("healthy");
  return [...cuisines];
}

function buildMethod(methodType, ingredients, time, name) {
  const featured = ingredients.filter(item => !PANTRY_INGREDIENTS.has(item)).slice(0, 4).join(", ");
  const cookTime = Math.max(5, time - 10);
  const methods = {
    pan: `Подготовьте ${featured}. Обжаривайте продукты на разогретой сковороде, помешивая и добавляя их по времени готовности. Доведите до вкуса и подавайте горячим примерно через ${cookTime} минут.`,
    oven: `Подготовьте ${featured}, выложите в форму и приправьте. Запекайте при 185–200 °C до румяности и полной готовности около ${cookTime} минут.`,
    boil: `Подготовьте ${featured}. Варите ингредиенты в подходящем количестве воды, добавляя более нежные продукты ближе к концу. Проверьте вкус и готовность перед подачей.`,
    stew: `Нарежьте и слегка обжарьте основные продукты: ${featured}. Добавьте немного воды или соуса и тушите под крышкой на слабом огне до мягкости около ${cookTime} минут.`,
    bake: `Соедините ${featured} в однородное тесто или массу. Переложите в подготовленную форму и выпекайте до уверенной золотистой корочки и сухой шпажки.`,
    "no-cook": `Подготовьте и нарежьте ${featured}. Соедините ингредиенты непосредственно перед подачей, аккуратно перемешайте и отрегулируйте вкус.`,
    grill: `Подготовьте ${featured}, слегка смажьте и приправьте. Обжаривайте на гриле или сухой сковороде порциями до выраженных полосок и готовности.`,
    steam: `Подготовьте ${featured}, распределите в пароварке или на решётке. Готовьте над паром до мягкости, затем приправьте и сразу подавайте.`
  };
  return methods[methodType] || `Подготовьте ингредиенты для блюда «${name}» и доведите их до готовности удобным способом.`;
}

function makeRecipe([name, ingredientLine, time, difficulty, methodType, mealType, mainLine]) {
  const ingredients = ingredientLine.split("|");
  const mainIngredients = mainLine.split("|");
  const recipe = {
    name,
    ingredients,
    time,
    difficulty,
    methodType,
    mealType,
    mainIngredients,
    icon: RECIPE_ICONS[mealType],
    description: `${name} — ${RECIPE_DESCRIPTIONS[mealType]}.`,
    method: buildMethod(methodType, ingredients, time, name)
  };
  recipe.cuisine = inferRecipeCuisine(recipe);
  return recipe;
}

